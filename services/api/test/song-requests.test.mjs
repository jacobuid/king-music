import test from 'node:test'
import assert from 'node:assert/strict'
import {worker,setup,seed,req} from './helpers.mjs'
const create=(body,profile='kid',user='u1')=>req('/api/song-requests',{profile,user,body})
const approve=ids=>req('/api/song-requests/approve',{body:{ids}})
test('kids request restricted library songs once; only adults in the same account can approve',async()=>{
 const {db,env}=setup();seed(db)
 let result=await worker.fetch(create({mediaId:'restricted',title:'Forged title'}),env);assert.equal(result.status,201);const first=await result.json()
 assert.equal((await(await worker.fetch(create({mediaId:'restricted'}),env)).json()).id,first.id)
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM song_requests').get().n,1)
 assert.equal(db.prepare('SELECT title FROM song_requests').get().title,'Restricted')
 assert.equal((await worker.fetch(create({mediaId:'foreign-song'}),env)).status,404)
 assert.equal((await worker.fetch(req('/api/song-requests/approve',{profile:'kid',body:{ids:[first.id]}}),env)).status,403)
 let foreign=await(await worker.fetch(req('/api/song-requests/approve',{profile:'foreign',user:'u2',body:{ids:[first.id]}}),env)).json();assert.equal(foreign.results[0].error,'Request not found')
 assert.equal((await worker.fetch(req('/api/media/restricted/play',{profile:'kid',body:{profileId:'kid'}}),env)).status,404)
 let listed=await(await worker.fetch(req('/api/song-requests'),env)).json();assert.equal(listed.requests[0].requester,'Child')
 let response=await(await worker.fetch(approve([first.id]),env)).json();assert.equal(response.results[0].ok,true)
 assert.equal(db.prepare("SELECT kids_allowed FROM media WHERE id='restricted'").get().kids_allowed,1)
 assert.equal((await worker.fetch(req('/api/media/restricted/play',{profile:'kid',body:{profileId:'kid'}}),env)).status,200)
 assert.equal((await(await worker.fetch(req('/api/song-requests'),env)).json()).requests.length,0)
 db.close()
})
test('adult approval queues YouTube import and callback grants kids access only for an approved request',async t=>{
 const {db,env}=setup();seed(db);const old=globalThis.fetch;t.after(()=>globalThis.fetch=old);globalThis.fetch=async()=>Response.json({queued:1})
 const child=await(await worker.fetch(create({videoId:'abcdefghijk',title:'New song',artist:'Artist',album:'Album',thumbnail:'https://evil.test/image'}),env)).json()
 assert.equal((await(await worker.fetch(req('/api/song-requests',{profile:'kid'}),env)).json()).requests[0].status,'pending')
 assert.equal((await worker.fetch(req('/api/discovery/song',{profile:'kid',body:{videoId:'abcdefghijk'}}),env)).status,403)
 const approved=await(await worker.fetch(approve([child.id]),env)).json();assert.equal(approved.results[0].ok,true)
 const job=db.prepare('SELECT * FROM import_jobs WHERE video_id=?').get('abcdefghijk');assert.equal(job.status,'queued')
 assert.equal(db.prepare('SELECT thumbnail_url FROM song_requests').get().thumbnail_url,null)
 const completion=new Request('https://music.test/api/internal/music/'+job.id,{method:'POST',headers:{Authorization:'Bearer test-service'},body:JSON.stringify({status:'ready',duration:180})})
 assert.equal((await worker.fetch(completion,env)).status,200)
 assert.equal(db.prepare('SELECT kids_allowed FROM media WHERE id=?').get(job.id).kids_allowed,1)
 db.close()
})
test('failed approval stays actionable, declined requests can be requested again, and queues are scoped',async t=>{
 const {db,env}=setup();seed(db);const old=globalThis.fetch;t.after(()=>globalThis.fetch=old);globalThis.fetch=async()=>new Response('{}',{status:503})
 const child=await(await worker.fetch(create({videoId:'abcdefghijk',title:'New song'}),env)).json()
 const failed=await(await worker.fetch(approve([child.id]),env)).json();assert.ok(failed.results[0].error)
 assert.equal(db.prepare('SELECT status FROM song_requests').get().status,'pending')
 assert.equal((await(await worker.fetch(req('/api/song-requests',{user:'u2',profile:'foreign'}),env)).json()).requests.length,0)
 await worker.fetch(req('/api/song-requests/decline',{body:{ids:[child.id]}}),env)
 assert.equal(db.prepare('SELECT status FROM song_requests').get().status,'declined')
 await worker.fetch(create({videoId:'abcdefghijk',title:'New song'}),env);assert.equal(db.prepare('SELECT status FROM song_requests').get().status,'pending')
 assert.equal((await worker.fetch(approve([]),env)).status,400)
 db.close()
})
