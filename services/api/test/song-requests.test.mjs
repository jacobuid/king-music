test('approved import failures return to the adult queue and can be retried',async t=>{
 const {db,env}=setup();seed(db);const old=globalThis.fetch;t.after(()=>globalThis.fetch=old);globalThis.fetch=async()=>Response.json({queued:1})
 const row=await(await worker.fetch(create({videoId:'abcdefghijk',title:'Retry song'}),env)).json()
 await worker.fetch(approve([row.id]),env)
 db.prepare("UPDATE import_jobs SET status='failed' WHERE video_id=?").run('abcdefghijk')
 const listed=await(await worker.fetch(req('/api/song-requests'),env)).json();assert.equal(listed.requests.length,1);assert.equal(listed.requests[0].importStatus,'failed')
 await worker.fetch(approve([row.id]),env);assert.equal(db.prepare('SELECT status FROM import_jobs').get().status,'queued')
 db.close()
})

test('playlist requests append existing and newly imported songs only after approval, including multiple destinations',async t=>{
 const {db,env}=setup();seed(db);const old=globalThis.fetch;t.after(()=>globalThis.fetch=old);globalThis.fetch=async()=>Response.json({queued:1})
 db.prepare('INSERT INTO playlists(id,profile_id,name) VALUES(?,?,?)').run('kids-mix','kid','Kids mix')
 db.prepare('INSERT INTO playlists(id,profile_id,name) VALUES(?,?,?)').run('kids-two','kid','Kids second')
 db.prepare('INSERT INTO playlists(id,profile_id,name) VALUES(?,?,?)').run('adults-mix','adult','Adult mix')
 let response=await worker.fetch(create({mediaId:'restricted',playlistId:'adults-mix'}),env);assert.equal(response.status,403)
 const local=await(await worker.fetch(create({mediaId:'restricted',playlistId:'kids-mix'}),env)).json()
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM playlist_tracks').get().n,0)
 await worker.fetch(approve([local.id]),env)
 assert.equal(db.prepare('SELECT media_id FROM playlist_tracks WHERE playlist_id=?').get('kids-mix').media_id,'restricted')
 const external=await(await worker.fetch(create({videoId:'abcdefghijk',title:'Requested import',playlistId:'kids-mix'}),env)).json()
 const again=await(await worker.fetch(create({videoId:'abcdefghijk',title:'Requested import',playlistId:'kids-two'}),env)).json();assert.equal(again.id,external.id)
 let listed=await(await worker.fetch(req('/api/song-requests',{profile:'kid'}),env)).json();assert.deepEqual(listed.requests.find(row=>row.id===external.id).playlistIds.sort(),['kids-mix','kids-two'])
 await worker.fetch(approve([external.id]),env)
 const job=db.prepare('SELECT * FROM import_jobs WHERE video_id=?').get('abcdefghijk')
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM playlist_tracks').get().n,1)
 const finish=()=>worker.fetch(new Request('https://music.test/api/internal/music/'+job.id,{method:'POST',headers:{Authorization:'Bearer test-service'},body:JSON.stringify({status:'ready',duration:180})}),env)
 assert.equal((await finish()).status,200);assert.equal((await finish()).status,200)
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM playlist_tracks WHERE media_id=?').get(job.id).n,2)
 assert.equal(db.prepare('SELECT kids_allowed FROM media WHERE id=?').get(job.id).kids_allowed,1)
 db.close()
})
test('adult external imports remember the destination and append on completion; foreign playlists are rejected',async t=>{
 const {db,env}=setup();seed(db);const old=globalThis.fetch;t.after(()=>globalThis.fetch=old);globalThis.fetch=async()=>Response.json({queued:1})
 db.prepare('INSERT INTO playlists(id,profile_id,name) VALUES(?,?,?)').run('target','adult','Target')
 db.prepare('INSERT INTO playlists(id,profile_id,name) VALUES(?,?,?)').run('foreign-target','foreign','Foreign')
 assert.equal((await worker.fetch(req('/api/discovery/song',{body:{videoId:'abcdefghijk',title:'Song',playlistId:'foreign-target'}}),env)).status,404)
 assert.equal((await worker.fetch(req('/api/discovery/song',{body:{videoId:'abcdefghijk',title:'Song',playlistId:'target'}}),env)).status,202)
 const job=db.prepare('SELECT * FROM import_jobs').get();assert.equal(db.prepare('SELECT playlist_id FROM import_playlist_tracks').get().playlist_id,'target')
 const finish=await worker.fetch(new Request('https://music.test/api/internal/music/'+job.id,{method:'POST',headers:{Authorization:'Bearer test-service'},body:JSON.stringify({status:'ready',duration:180})}),env);assert.equal(finish.status,200)
 assert.equal(db.prepare('SELECT media_id FROM playlist_tracks WHERE playlist_id=?').get('target').media_id,job.id)
 assert.equal(db.prepare('SELECT kids_allowed FROM media WHERE id=?').get(job.id).kids_allowed,0)
 db.close()
})
